def inner_markup(svg: str) -> str:
    body = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
    m = re.search(r"<svg[^>]*>(.*)</svg>", body, re.S)
    if not m:
        raise ValueError("no svg body")
    inner = m.group(1)
    inner = re.sub(r"\s+", " ", inner).strip()
    inner = inner.replace(" />", "/>")
    return inner


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    src = Path(sys.argv[1])
    out: dict[str, str] = {}
    missing = []
    for key, name in ICONS.items():
        f = src / f"{name}.svg"
        if not f.is_file():
            missing.append(name)
            continue
        out[key] = inner_markup(f.read_text(encoding="utf-8"))
    if missing:
        print("missing:", ", ".join(missing), file=sys.stderr)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    header = (
        "/* Icon paths from Lucide (https://lucide.dev), ISC License.\n"
        " * Copyright (c) Lucide Contributors 2022; portions (c) Cole Bemis 2013-2022 (Feather, MIT).\n"
        " * Generated by interview/Scripts/vendor_play_icons.py. */\n"
    )
    OUT.write_text(
        header + "window.SD_ICONS = " + json.dumps(out, indent=0, sort_keys=True) + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(out)} icons)")
    return 0 if not missing else 1


if __name__ == "__main__":
    raise SystemExit(main())
